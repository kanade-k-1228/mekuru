import type { Layer, Psd } from "ag-psd";
import { lstat, mkdir, readFile, rmdir, unlink, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { readArtwork, rasterize } from "./portrait/psd-image.ts";
import { animated, assetName, kinds, selectable, validateManifest, type PortraitKind, type PsdManifest } from "./portrait/psd-schema.ts";

const annotated = new RegExp(`^(.*?) \\[(${kinds.join("|")})\\]$`);

/** Validate the convention before rendering or writing anything. */
export function parsePortrait(psd: Psd) {
  const manifest: PsdManifest = { width: psd.width, height: psd.height, layers: [] };
  const artwork: { src: string; layer: Layer; ancestors: Layer[] }[] = [];
  for (const layer of psd.children ?? []) {
    const match = annotated.exec(layer.name ?? "");
    if (!match) throw new Error(`Expected name [${kinds.join("|")}]: ${layer.name}`);
    const kind = match[2] as PortraitKind;
    const name = assetName(match[1], kind !== "fixed");
    if (!selectable(kind)) {
      const src = `${name}.png`;
      artwork.push({ src, layer, ancestors: [] });
      manifest.layers.push({ name, kind, initial: !layer.hidden, options: [{ name, frames: [src] }] });
      continue;
    }
    if (!layer.children?.length) throw new Error(`Empty group: ${name}`);
    const visible = layer.children.filter((c) => !c.hidden);
    if (visible.length > 1) throw new Error(`Multiple visible options: ${name}`);
    const options = layer.children.map((child) => {
      const option = assetName(child.name ?? "");
      if (animated(kind) && child.children) {
        const frames = [...child.children].sort((a, b) => Number(a.name) - Number(b.name));
        if (!frames.length || frames.some((f, i) => f.name !== String(i))) throw new Error(`Expected consecutive frames 0..N: ${name}/${option}`);
        return {
          name: option,
          frames: frames.map((frame, i) => {
            const src = `${name}/${option}/${i}.png`;
            artwork.push({ src, layer: frame, ancestors: [child, layer] });
            return src;
          }),
        };
      }
      const src = `${name}/${option}.png`;
      artwork.push({ src, layer: child, ancestors: [layer] });
      return { name: option, frames: [src] };
    });
    manifest.layers.push({ name, kind, options, initial: layer.hidden ? null : (visible[0]?.name ?? null) });
  }
  validateManifest(manifest);
  return { manifest, artwork };
}

/** PSD parsing and rasterization happen once, outside video rendering. */
export async function exportPsd(input: string, output: string): Promise<PsdManifest> {
  const psd = await readArtwork(input);
  const { manifest, artwork } = parsePortrait(psd);
  const raster = rasterize(psd);
  const images = new Map<string, Buffer>();
  for (const { src, layer, ancestors } of artwork) {
    const bytes = await raster.render(layer);
    for (const parent of ancestors) raster.apply(bytes, parent);
    images.set(src, await raster.png(bytes));
  }
  await writeAssets(resolve(output), manifest, images);
  return manifest;
}

async function writeAssets(out: string, manifest: PsdManifest, images: ReadonlyMap<string, Buffer>): Promise<void> {
  let previous: unknown;
  try {
    previous = JSON.parse(await readFile(join(out, "portrait.json"), "utf8"));
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
  }
  let oldFiles: string[] = [];
  if (previous !== undefined) {
    validateManifest(previous);
    oldFiles = previous.layers.flatMap((l) => l.options.flatMap((o) => o.frames));
  }
  // Do not follow symlinks when updating generated assets.
  const checkPath = async (path: string) => {
    let current = out;
    for (const segment of ["", ...path.split("/")]) {
      current = join(current, segment);
      try {
        if ((await lstat(current)).isSymbolicLink()) throw new Error(`Output contains a symlink: ${current}`);
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
      }
    }
  };
  const stale = oldFiles.filter((src) => !images.has(src));
  for (const path of [...images.keys(), ...stale, "portrait.json", "portrait.d.ts"]) await checkPath(path);
  for (const [src, bytes] of images) {
    const dest = join(out, src);
    await mkdir(dirname(dest), { recursive: true });
    await writeFile(dest, bytes);
  }
  const fields = manifest.layers
    .filter((l) => l.kind !== "fixed")
    .map((l) => `  ${JSON.stringify(l.name)}?: ${l.kind === "toggle" ? "boolean" : `${l.options.map((o) => JSON.stringify(o.name)).join(" | ")} | null`};`);
  await writeFile(join(out, "portrait.d.ts"), `// Generated by mekuru-psd. Do not edit.\nexport interface LayerProps {\n${fields.join("\n")}\n}\n`);
  for (const src of stale)
    await unlink(join(out, src)).catch((error: NodeJS.ErrnoException) => {
      if (error.code !== "ENOENT") throw error;
    });
  // Remove only empty directories formerly containing generated images, deepest first.
  const dirs = new Set(
    stale.flatMap((p) =>
      p
        .split("/")
        .slice(0, -1)
        .map((_, i, parents) => parents.slice(0, i + 1).join("/")),
    ),
  );
  for (const dir of [...dirs].sort((a, b) => b.split("/").length - a.split("/").length))
    await rmdir(join(out, dir)).catch((error: NodeJS.ErrnoException) => {
      if (!["ENOENT", "ENOTEMPTY", "EEXIST"].includes(error.code ?? "")) throw error;
    });
  await writeFile(join(out, "portrait.json"), `${JSON.stringify(manifest, null, 2)}\n`);
}
